from dataclasses import dataclass
from enum import StrEnum

from agentic_core.director.context_manager import ProjectSummary


class DirectorAction(StrEnum):
    RESEARCH = "research_topic"
    WRITE_SCRIPT = "generate_script"
    AWAIT_HUMAN = "await_script_approval"
    GENERATE_AUDIO = "generate_audio"
    DONE = "done"
    STOP = "stop"


@dataclass(frozen=True)
class PipelineState:
    """What already exists for the project, as seen by the api layer."""

    has_research: bool = False
    has_script: bool = False
    script_gate_status: str | None = None  # pending | approved | rejected
    has_audio: bool = False


@dataclass(frozen=True)
class DirectorDecision:
    action: DirectorAction
    reason: str


class StudioDirector:
    """
    The Director is the agentic decision-making boundary: given the
    assembled ProjectSummary (Context Manager) and the current pipeline
    state, it decides the single next step.

    Week 2 scope: a deterministic policy over the Week 2 pipeline
    (research -> script -> human approval -> audio). Content itself
    (research notes, scripts) is LLM-generated by the tools this
    decision dispatches; the *ordering* is kept deterministic so the
    pipeline is predictable and testable. The returned `reason` is
    recorded verbatim as the audit trail's agent_decision, which is
    what the Agent Chat shows on its brain lines.
    """

    def decide(
        self,
        summary: ProjectSummary,
        state: PipelineState,
    ) -> DirectorDecision:
        if summary.budget_limit is not None and round(summary.budget_spent, 6) >= round(
            summary.budget_limit, 6
        ):
            return DirectorDecision(
                DirectorAction.STOP,
                f"Budget exhausted (${summary.budget_spent:.2f} of "
                f"${summary.budget_limit:.2f}); stopping before further tool calls.",
            )

        if state.script_gate_status == "rejected":
            return DirectorDecision(
                DirectorAction.STOP,
                "The script was rejected by a human reviewer; stopping so it "
                "can be revised rather than producing audio for it.",
            )

        if not state.has_research:
            memory_note = (
                f" Found {len(summary.prior_memory)} related memories to build on."
                if summary.prior_memory
                else " No prior memory for this topic, starting fresh."
            )
            return DirectorDecision(
                DirectorAction.RESEARCH,
                f"Researching '{summary.topic}' before writing anything, so the "
                f"script is grounded in facts.{memory_note}",
            )

        if not state.has_script:
            return DirectorDecision(
                DirectorAction.WRITE_SCRIPT,
                f"Research is in. Writing a {summary.duration_seconds}s "
                f"{summary.aspect_ratio} script, then routing it to a human "
                "for approval before spending on audio.",
            )

        if state.script_gate_status in (None, "pending"):
            return DirectorDecision(
                DirectorAction.AWAIT_HUMAN,
                "Script is ready. Waiting for human approval before audio.",
            )

        if not state.has_audio:
            return DirectorDecision(
                DirectorAction.GENERATE_AUDIO,
                "Script approved. Generating narration, word timestamps and "
                "semantic beats (audio-first, so visuals can sync to it later).",
            )

        return DirectorDecision(
            DirectorAction.DONE,
            "Week 2 pipeline complete: approved script and timed narration ready.",
        )
