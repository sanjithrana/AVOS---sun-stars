import { expect, test, type Page } from "@playwright/test";

// These specs drive the manual QA / repair UI, so the workflow's automatic QA agent (v12) is turned off while they
// run and turned back on afterwards (GPU page → generation limits).
test.beforeAll(async ({ request }) => {
  await request.put(`${process.env.E2E_API_URL || "http://localhost:8001/api/v1"}/gpu/limits`, { data: { auto_qa: false } });
});
test.afterAll(async ({ request }) => {
  await request.put(`${process.env.E2E_API_URL || "http://localhost:8001/api/v1"}/gpu/limits`, { data: { auto_qa: true } });
});


/**
 * Week 3 Day 14 - QADashboard, driven through the real UI: once a shot
 * has generated candidates, "Run QA" dispatches run_qa_committee through
 * the audited Gateway and the panel updates live (SSE QA_PASSED, no
 * reload) with the 6 dimension scores (2 real, 4 TODO placeholders).
 *
 * The mock Video generator and the QA committee's geometry check share
 * the same SHOT_TYPE_SCALE mapping (agentic_core/pipelines/qa/committee.py),
 * so a shot generated by the mock pipeline always earns a real PASS here
 * - that agreement is what a repair-ladder e2e test would have to break
 * artificially. Forcing a FAIL and proving the ladder escalates
 * Micro -> Macro -> Human on 3 attempts (AVOS-03 v1.1 s14.6) is instead
 * covered directly against the durable Postgres counter in
 * api/tests/test_repair_ladder.py, which is the stronger guarantee: it
 * proves the ladder from the database state, not from whatever a mock
 * renderer happens to produce this week.
 */

function trackErrors(page: Page): string[] {
  const errors: string[] = [];
  page.on("console", (msg) => {
    if (msg.type() === "error") errors.push(`console: ${msg.text()}`);
  });
  page.on("pageerror", (err) => errors.push(`pageerror: ${err.message}`));
  return errors;
}

async function createProject(page: Page, topic: string) {
  await page.goto("/facts");
  await page.getByRole("button", { name: "New Project" }).first().click();
  await page.getByLabel("Topic").fill(topic);
  await page.getByLabel("Duration (sec)").fill("30");
  // No per-shot clips: keeps this spec offline/deterministic (mock
  // images); final-video.spec.ts covers the video providers.
  await page.locator("#image-provider").selectOption("");   // deterministic placeholder pictures (the QA checks agree by construction)
  await page.locator("#video-provider").selectOption("");
  await page.getByRole("button", { name: "Create Project" }).click();
  await expect(page).toHaveURL(/\/project\/[0-9a-f-]{36}$/, { timeout: 30_000 });
}

test("QA dashboard: Run QA scores a generated shot live and shows no repair affordance on PASS", async ({
  page,
}) => {
  const errors = trackErrors(page);
  const topic = `QA dashboard ${Date.now()}`;

  await createProject(page, topic);

  await page.getByTestId("generate-button").click();
  const review = page.getByRole("link", { name: /Review in Studio/ });
  await expect(review).toBeVisible({ timeout: 30_000 });
  await review.click();

  await page.getByTestId("script-approval").getByRole("button", { name: "Approve" }).click();

  const cards = page.getByTestId("shot-card");
  await expect(cards.first()).toBeVisible({ timeout: 30_000 });

  // The pipeline generates every shot's candidates itself, so QA has
  // something to score (run_qa_committee needs candidate_index 0).
  const monitor = page.getByTestId("generation-monitor");
  const firstRow = monitor.getByTestId("generation-row").first();
  await expect(firstRow).toHaveAttribute("data-shot-status", "QA_PENDING", { timeout: 120_000 });

  // Selecting the first shot (default selection) shows its QA dashboard.
  const dashboard = page.getByTestId("qa-dashboard");
  await expect(dashboard).toBeVisible();
  await expect(dashboard.getByTestId("qa-empty")).toBeVisible();

  await dashboard.getByTestId("run-qa").click();

  // Live update over SSE (QA_PASSED): no reload, the verdict and all 6
  // dimensions (2 real + 4 TODO placeholders) appear.
  const result = dashboard.getByTestId("qa-result");
  await expect(result).toBeVisible({ timeout: 15_000 });
  await expect(dashboard.getByTestId("qa-verdict")).toHaveAttribute("data-verdict", "PASS");
  await expect(result.getByTestId("qa-dimension")).toHaveCount(6);
  await expect(result.getByTestId("qa-dimension").filter({ hasText: "Visual" })).toBeVisible();
  await expect(result.getByTestId("qa-dimension").filter({ hasText: "Geometry" })).toBeVisible();

  // A PASS has nothing to repair.
  await expect(dashboard.getByTestId("repair-panel")).toHaveCount(0);

  // Re-running QA is idempotent from the UI's point of view: still one
  // result, same verdict, no duplicate rows.
  await dashboard.getByTestId("run-qa").click();
  await expect(result.getByTestId("qa-dimension")).toHaveCount(6);

  expect(errors).toEqual([]);
});
